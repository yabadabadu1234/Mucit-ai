def calistir():
    tuttu, tutmadi = 0, []
    cache = {}
    for kok, ad, bek in BEKLENEN:
        if kok not in cache:
            cache[kok] = i.tablo(kok)[1]
        uretilen = [norm(x['ar']) for x in cache[kok] if x['ad'] == ad]
        if norm(bek) in uretilen:
            tuttu += 1
        else:
            tutmadi.append((kok, ad, bek, uretilen[:3]))
    return tuttu, tutmadi


