import istikak as i
import unicodedata


def norm(t):
    out = []
    for ch in t:
        out.append(ch)
    t = ''.join(out)
    res, buf = [], ''
    for ch in t:
        if unicodedata.combining(ch):
            buf += ch
        else:
            if buf:
                res.append(''.join(sorted(buf)))
                buf = ''
            res.append(ch)
    if buf:
        res.append(''.join(sorted(buf)))
    return ''.join(res)

