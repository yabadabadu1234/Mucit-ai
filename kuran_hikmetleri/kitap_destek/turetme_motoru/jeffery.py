def sade(w):
    w = K.sade(w)
    w = re.sub('[أإآٱ]', 'ا', w).replace('ة', 'ه').replace('ى', 'ي').replace('ئ', 'ي').replace('ؤ', 'و')
    return re.sub(r'^ال', '', w)


def girdiler():
    t = subprocess.run(['pdftotext', PDF, '-'], capture_output=True).stdout.decode('utf-8', 'ignore')
    t = re.sub(r'[\x00-\x08\x0b-\x1f\x7f]', '', t)
    L = t.split('\n')
    bas = next(i for i, l in enumerate(L) if 'THE FOREIGN WORDS' in l)
    H = []
    for i in range(bas, len(L)):
        m = re.search(r'\(([^()]{2,45})\)\s*[.,]?\s*$', L[i])
        if not m:
            continue
        nxt = ' '.join(x.strip() for x in L[i + 1:i + 4] if x.strip())[:70]
        if re.match(r'^[ivxlcdm]+,\s*\d', nxt) and not re.search(r'[a-z]{4,} [a-z]{3,} [a-z]{3,}', L[i][:m.start()]):
            H.append((i, m.group(1).strip()))
    sonuc = []
    for n, (i, tr) in enumerate(H):
        j = H[n + 1][0] if n + 1 < len(H) else len(L)
        metin = ' '.join(x.strip() for x in L[i + 1:j] if x.strip())
        ilk = metin[:700]
        dil = [d for d in DIL if d in ilk]
        sonuc.append({'kaynak': "Arthur Jeffery, The Foreign Vocabulary of the Qur'ān (Baroda 1938; Brill yeniden basımı, yazıya geçirilmiş metin; Arapça yazılar yazı tipi bozuk olduğundan alınmadı)", 'translit': tr,
                      'ayet_atiflari': re.split(r'\.', metin, 1)[0][:200], 'ilk_baslik_dilleri': dil, 'metin': metin, 'arapca': ARAPCA.get(len(sonuc), '')})
    return sonuc


def yukle():
    return {sade(e['arapca']): e for e in girdiler() if e['arapca']}
